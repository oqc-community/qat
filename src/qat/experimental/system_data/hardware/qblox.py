"""Qblox-specific derived view of canonical system data.

This module describes the configuration of Qblox hardware with a single data
structure that mirrors the physical RF chain of a Qblox Cluster. Qblox modules
are control hardware devices which can control many qubits and perform readout
depending on the module type. Each tone generated by the module is called a
generator (aka physical port). A generator is a subsection of the module (often
a sequencer + local oscillator). The generator is responsible for control of a
single mode of a qubit and can be mapped to a ``frame``. This configuration
dictates the boundaries of the generated tone and is used for legalisation and
for lowering the pulse dialect to the Q1asm dialect (Qblox IR).

As an example, a single output tone is produced by combining a local oscillator with a
sequencer's NCO
(e.g. an LO at 4.4 GHz mixed with an NCO at 240 MHz yields a 4.64 GHz output). Each such
tone-generation unit is captured as a :class:`~qat.experimental.system_data.hardware.base.
Generator` bound to a physical port. The :class:`QbloxHardwareView` ties the generators
together into a derived view of
:class:`~qat.experimental.system_data.canonical.schema.CanonicalSystemData`.

The model follows the hardware building blocks documented by Qblox (see, for example, the
`QRM-RF architecture
<https://docs.qblox.com/en/main/products/architecture/modules/qrm_rf.html>`_): a Cluster is
populated with modules (``QCM``, ``QCM-RF``, ``QRM``, ``QRM-RF``, ``QRC``); each module
exposes one or more RF ports; and each port is fed by a set of sequencers and, on RF
modules, one or more local oscillators.
"""

