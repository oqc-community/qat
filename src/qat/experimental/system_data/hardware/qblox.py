class QbloxModuleType(str, Enum):
    """The Qblox Cluster module types supported by this view.

    :cvar QCM: Baseband Qubit Control Module.
    :cvar QCM_RF: RF Qubit Control Module.
    :cvar QRM: Baseband Qubit Readout Module.
    :cvar QRM_RF: RF Qubit Readout Module.
    :cvar QRC: RF Qubit Readout and Control Module.
    """

    QCM = "QCM"
    QCM_RF = "QCM-RF"
    QRM = "QRM"
    QRM_RF = "QRM-RF"
    QRC = "QRC"


@dataclass(frozen=True, slots=True)
class QbloxModuleSpec:
    """Static description of a Qblox module's RF chain capabilities.

    This captures the invariant limits of a module type (previously spread across the
    ``*Description`` models in ``qat.backend.qblox.target_data``) grouped by the physical
    structure they describe.

    .. note:: Whether a module up/down-converts (is "RF") is *not* stored as a flag: it is
       implied by the module's output frequency range. Likewise, whether a local oscillator
       is shared is implied by the generators mapping the same
       :class:`QBloxLocalOscillator` onto multiple sequencers.

    :ivar module_type: The module type this spec describes, or ``None`` for an unresolved
        module.
    :ivar number_of_control_sequencers: Number of sequencers dedicated to control tones.
    :ivar number_of_readout_sequencers: Number of sequencers capable of acquisition.
    :ivar number_of_outputs: Number of physical output ports.
    :ivar number_of_inputs: Number of physical input ports.
    :ivar max_binned_acquisitions: Maximum number of binned acquisitions the module can
        store, or ``None`` for control-only modules.
    :ivar scope_sample_size_range: Inclusive scope-acquisition trace sample-size bounds, or
        ``None`` for control-only modules.
    """

    module_type: QbloxModuleType | None
    number_of_control_sequencers: int
    number_of_readout_sequencers: int
    number_of_outputs: int
    number_of_inputs: int
    max_binned_acquisitions: int | None
    scope_sample_size_range: tuple[int, int] | None

    def build_sequencers(
        self, config: Mapping[str, Any] | None = None
    ) -> tuple[Sequencer, ...]:
        """Build the full fixed sequencer set for a module of this type.

        When a legacy ``QbloxConfig`` payload is supplied, each sequencer is configured from
        the matching ``sequencers[index]`` entry (NCO, AWG, marker and, for readout
        sequencers, acquisition settings). Missing entries fall back to defaults.

        :param config: Optional legacy ``QbloxConfig`` payload for the module.
        :returns: The control sequencers followed by the readout sequencers, each indexed
            contiguously from zero.
        """

        sequencer_payloads = _sequencer_payloads(config)
        sequencers: list[Sequencer] = []
        index = 0
        for _ in range(self.number_of_control_sequencers):
            sequencers.append(QBloxSequencer.create(index, sequencer_payloads.get(index)))
            index += 1
        for _ in range(self.number_of_readout_sequencers):
            sequencers.append(
                QBloxReadoutSequencer.create(index, sequencer_payloads.get(index))
            )
            index += 1
        return tuple(sequencers)


